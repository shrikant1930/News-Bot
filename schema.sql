-- Existing installations may have the original three-status CHECK
-- constraint with an automatically assigned name. Replace only the CHECK
-- constraints that apply to digest_log.status, then add the pinned-safe one.
do $$
declare
  constraint_name text;
begin
  for constraint_name in
    select con.conname
    from pg_constraint con
    join pg_class rel on rel.oid = con.conrelid
    join pg_namespace ns on ns.oid = rel.relnamespace
    where ns.nspname = 'public'
      and rel.relname = 'digest_log'
      and con.contype = 'c'
      and pg_get_constraintdef(con.oid) like '%status%'
  loop
    execute format('alter table public.digest_log drop constraint %I', constraint_name);
  end loop;
end $$;

