create or replace function public.cleanup_forex_news_retention()
returns void
language sql
security definer
set search_path = public
as $$
  delete from public.alert_log where sent_at < now() - interval '60 days';
  delete from public.result_alert_log
    where coalesce(sent_at, claimed_at) < now() - interval '60 days';
  delete from public.digest_log where created_at < now() - interval '60 days';
  delete from public.economic_events
    where time_utc < now() - interval '60 days' and status = 'not_in_feed';
$$;

