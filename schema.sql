-- The dedicated results GitHub Actions workflow is dispatched every minute by
-- the Supabase pg_cron + pg_net + Vault bridge below. It does not alter the
-- existing alert or calendar-sync schedules. See README for one-time Vault
-- secret setup and the scheduler command.

create or replace function public.dispatch_forex_news_results()
returns bigint
language plpgsql
security definer
set search_path = public, vault, net
as $$
declare
  dispatch_url text;
  github_token text;
  request_id bigint;
begin
  select decrypted_secret into dispatch_url
  from vault.decrypted_secrets
  where name = 'github_results_dispatch_url';

  select decrypted_secret into github_token
  from vault.decrypted_secrets
  where name = 'github_actions_dispatch_token';

  if dispatch_url is null or github_token is null then
    raise exception 'Missing Vault secrets for the results workflow dispatch';
  end if;

  select net.http_post(
    url := dispatch_url,
    headers := jsonb_build_object(
      'Authorization', 'Bearer ' || github_token,
      'Accept', 'application/vnd.github+json',
      'X-GitHub-Api-Version', '2022-11-28',
      'User-Agent', 'supabase-forex-news-results'
    ),
    body := jsonb_build_object('ref', 'main'),
    timeout_milliseconds := 5000
  ) into request_id;

  return request_id;
end;
$$;

revoke execute on function public.dispatch_forex_news_results() from public, anon, authenticated;

